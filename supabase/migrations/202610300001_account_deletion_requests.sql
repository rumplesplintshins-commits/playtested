-- Account deletion requests are intentionally staged before destructive erasure.
-- This gives Playtested an auditable, authenticated request while the final
-- per-table anonymisation routine is reviewed against the production schema.

create table if not exists public.account_deletion_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  requested_at timestamptz not null default now(),
  status text not null default 'pending' check (status in ('pending', 'processing', 'completed', 'cancelled')),
  completed_at timestamptz,
  operator_notes text
);

create unique index if not exists account_deletion_requests_one_open_per_user
  on public.account_deletion_requests (user_id)
  where status in ('pending', 'processing');

alter table public.account_deletion_requests enable row level security;

revoke all on table public.account_deletion_requests from anon, authenticated;
grant select on table public.account_deletion_requests to authenticated;

create policy "Users can read their own deletion requests"
  on public.account_deletion_requests
  for select
  to authenticated
  using (user_id = auth.uid());

create or replace function public.request_account_deletion()
returns table (request_id bigint, request_status text, requested_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_request public.account_deletion_requests%rowtype;
begin
  if v_user_id is null then
    raise exception 'You must be signed in to request account deletion.';
  end if;

  select * into v_request
  from public.account_deletion_requests
  where user_id = v_user_id
    and status in ('pending', 'processing')
  order by requested_at desc
  limit 1;

  if v_request.id is null then
    insert into public.account_deletion_requests (user_id)
    values (v_user_id)
    returning * into v_request;
  end if;

  return query
  select v_request.id, v_request.status, v_request.requested_at;
end;
$$;

revoke all on function public.request_account_deletion() from public, anon;
grant execute on function public.request_account_deletion() to authenticated;
